#!/usr/bin/env python3
"""Generate the Prove2Me platform tree for one goal theorem by skeleton subtraction.
Usage: [P2M_GOAL=<qualified theorem>] generate.py <repo_dir> <extract_dir> <out_dir>"""
import json, sys, re, os, collections
repo, ext, out = sys.argv[1:4]
GOAL = os.environ.get('P2M_GOAL', 'PalomaMax2SAT.UgcBarrier.ugc_barrier')   # fully qualified goal theorem
GOAL_SHORT = GOAL.rsplit('.', 1)[1]
GOAL_MODULE = GOAL.rsplit('.', 1)[0]
DEF_NAME = 'PalomaMax2SAT_DegreeFormula'   # definition bundle name
THM_NAME = GOAL
THM_SLUG = THM_NAME.replace('.', '_')

rows = [json.loads(l) for l in open(f'{ext}/decl_graph.jsonl')]
by = {r['name']: r for r in rows}
ctors = collections.defaultdict(list)
for r in rows:
    if r['kind'] == 'ctor': ctors[r['name'].rsplit('.', 1)[0]].append(r['name'])

def closure(roots, follow):
    seen, st = set(), list(roots)
    while st:
        n = st.pop()
        if n in seen or n not in by: continue
        seen.add(n); r = by[n]
        st += follow(r)
        if r['kind'] == 'inductive': st += ctors[n]
    return seen

reach = closure([GOAL], lambda r: r['typeDeps'] + r['valueDeps'])

def mod_file(m):
    return os.path.join(repo, *m.split('.')) + '.lean' if m != 'Solution' else os.path.join(repo, 'Solution.lean')

def load_decls(m):
    name = m.split('.')[-1]
    facts = [json.loads(l) for l in open(f'{ext}/sketch_info.{name}.jsonl')]
    return [f for f in facts if f['kind'] == 'decl']

mods = sorted({by[n]['module'] for n in reach if by[n]['startLine'] > 0})
decls = {m: load_decls(m) for m in mods}
data = {m: open(mod_file(m), 'rb').read() for m in mods}

def unit(n):
    r = by[n]; m = r['module']
    if r['startLine'] == 0: return None
    for i, f in enumerate(decls[m]):
        if f['declStart']['line'] <= r['startLine'] <= f['declEnd']['line']:
            return (m, i)
    raise SystemExit(f'no decl fact for {n}')

# Def-material: reachable defs/inductives (non-private), plus theorems cited by their types/bodies
defmat = {n for n in reach if by[n]['kind'] in ('def', 'inductive') and by[n]['startLine'] > 0}
def_closure = closure(sorted(defmat), lambda r: r['typeDeps'] + r['valueDeps'])
bundle_units = {unit(n) for n in def_closure if unit(n)}
bundle_units.discard(None)
# helper theorems = reachable theorems not in bundle, not goal
goal_unit = unit(GOAL)
inline_units = {unit(n) for n in reach if by[n]['kind'] == 'theorem' and unit(n)} - bundle_units - {goal_unit}
print('bundle modules:', collections.Counter(m for m, _ in bundle_units))
print('bundle units', len(bundle_units), 'inline units', len(inline_units))

def strip_header(txt):
    lines = txt.split('\n')
    keep = []
    for l in lines:
        s = l.strip()
        if s == 'module': continue
        if s.startswith('public import ') or s.startswith('import '): continue
        if s.startswith('@[expose] public section'): continue
        keep.append(l)
    return '\n'.join(keep)

def subtract(m, selected):
    b = data[m]; cuts = []
    for i, f in enumerate(decls[m]):
        if (m, i) not in selected:
            cuts.append((f['declStart']['offset'], f['declEnd']['offset']))
    res = bytearray(); pos = 0
    for a, e in sorted(cuts):
        res += b[pos:a]; pos = e
    res += b[pos:]
    txt = res.decode('utf-8')
    txt = strip_header(txt)
    return re.sub(r'\n{3,}', '\n\n', txt).strip() + '\n'

# module order: import topological (by the source `public import` lines)
def imports(m):
    t = data[m].decode('utf-8')
    return [l.split()[-1] for l in t.split('\n') if l.startswith('public import PalomaMax2SAT')]
order, seen = [], set()
def visit(m):
    if m in seen: return
    seen.add(m)
    for d in imports(m):
        if d in data: visit(d)
    order.append(m)
for m in mods: visit(m)

os.makedirs(f'{out}/Definitions', exist_ok=True)
os.makedirs(f'{out}/Theorems', exist_ok=True)
os.makedirs(f'{out}/Solutions', exist_ok=True)
hdr = lambda s: f'-- Generated by skeleton subtraction from the paloma repository: {s}\n'

# Definitions bundle (one module here)
bmods = [m for m in order if any(bm == m for bm, _ in bundle_units)]
parts = ['import Mathlib', '']
for m in bmods:
    parts.append(f'section Bundle_{m.split(".")[-1]}')
    parts.append(subtract(m, {u for u in bundle_units if u[0] == m}))
    parts.append(f'end Bundle_{m.split(".")[-1]}\n')
bundle_text = hdr('Definitions bundle') + '\n'.join(parts)
open(f'{out}/Definitions/Def_{DEF_NAME}.lean', 'w').write(bundle_text)

# goal statement/proof
gm = by[GOAL]['module']; gf = decls[gm][goal_unit[1]]
gb = data[gm]
stmt = gb[gf['declStart']['offset']:gf['valStart']['offset']].decode()
proof = gb[gf['valStart']['offset']:gf['declEnd']['offset']].decode()
assert stmt.lstrip().startswith('theorem ' + GOAL_SHORT), stmt[:60]
stmt_body = stmt.strip()[len('theorem ' + GOAL_SHORT):]
# opens in effect at the goal in the source
opens = [l.strip() for l in gb.decode().split('\n') if l.startswith('open ')]
print('opens at goal:', opens)
preamble = 'import Mathlib\nimport Definitions.Def_' + DEF_NAME + '\n' + '\n'.join(opens)
formal = 'theorem ' + THM_NAME + stmt_body.rstrip() + ' := by sorry\n'
thm_text = hdr('Theorems stub') + preamble + '\n\n' + formal
open(f'{out}/Theorems/Thm_{THM_SLUG}.lean', 'w').write(thm_text)

# Solution
sparts = ['import Mathlib', f'import Definitions.Def_{DEF_NAME}', '']
for m in order:
    sel = {u for u in inline_units if u[0] == m}
    if not sel: continue
    sparts.append(f'section Inline_{m.split(".")[-1]}')
    sparts.append(subtract(m, sel))
    sparts.append(f'end Inline_{m.split(".")[-1]}\n')
sol = '\n'.join(opens) + '\n' if opens else ''
sol = '\n'.join(sparts) + '\n' + '\n'.join(f'open {o[5:]} in' for o in opens) + '\ntheorem solution' + stmt_body.rstrip() + ' ' + proof.rstrip() + '\n'
open(f'{out}/Solutions/Sol_{THM_SLUG}.lean', 'w').write(hdr('Solution') + sol)
json.dump({'definition_name': DEF_NAME, 'theorem_name': THM_NAME, 'slug': THM_SLUG,
           'preamble': preamble, 'formal_statement': formal}, open(f'{out}/upload_goal.json', 'w'), indent=1, ensure_ascii=False)
print('modules in solution:', [m for m in order if any(u[0]==m for u in inline_units)])
